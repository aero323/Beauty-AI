export const translateText = (input: string, language: Language) => {
  const sourceInput = restoreSourceText(input);
  if (language === 'zh') return sourceInput;

  const dictionary = dictionaries[language];
  const trimmed = sourceInput.trim();
  if (!trimmed) return sourceInput;

  const exact = dictionary[trimmed];
  if (exact) return preserveSpacing(sourceInput, exact);

  const templated = translateTemplate(trimmed, language);
  if (templated) return preserveSpacing(sourceInput, templated);

  if (!hasCjk(trimmed)) return sourceInput;

  let translated = trimmed;
  const keys = Object.keys(dictionary).filter(key => key.length > 2).sort((a, b) => b.length - a.length);
  for (const key of keys) {
    if (translated.includes(key)) {
      translated = translated.split(key).join(dictionary[key]);
    }
  }

  return preserveSpacing(sourceInput, translated);
};

const shouldSkipTextNode = (node: Text) => {
  const parent = node.parentElement;
  if (!parent) return true;
  if (skipTags.has(parent.tagName)) return true;
  if (parent.closest('[data-i18n-skip="true"]')) return true;
  if (parent.isContentEditable) return true;
  return false;
};

const translateTextNode = (node: Text, language: Language) => {
  if (shouldSkipTextNode(node)) return;
  const current = node.nodeValue ?? '';
  if (!current.trim()) return;

  const previousOriginal = textNodeOriginals.get(node);
  const original = getTextNodeSource(current, previousOriginal);
  if (previousOriginal !== original) {
    textNodeOriginals.set(node, original);
  }

  const next = translateText(original, language);
  if (node.nodeValue !== next) {
    node.nodeValue = next;
  }
};

const translateElementAttributes = (element: Element, language: Language) => {
  if (element.closest('[data-i18n-skip="true"]')) return;

  const originals = attrOriginals.get(element) ?? {};
  let changed = false;

  for (const attr of supportedAttributes) {
    const current = element.getAttribute(attr);
    if (!current) continue;

    const original = getTextNodeSource(current, originals[attr]);
    if (originals[attr] !== original) {
      originals[attr] = original;
      changed = true;
    }

    const next = translateText(original, language);
    if (current !== next) {
      element.setAttribute(attr, next);
    }
  }

  if (changed) {
    attrOriginals.set(element, originals);
  }
};

const translateTree = (root: ParentNode, language: Language) => {
  isApplyingTranslation = true;
  document.documentElement.lang = language === 'zh' ? 'zh-CN' : language;
  document.documentElement.dataset.language = language;

  const walker = document.createTreeWalker(root as Node, NodeFilter.SHOW_TEXT);
  const nodes: Text[] = [];
  while (walker.nextNode()) {
    nodes.push(walker.currentNode as Text);
  }

  nodes.forEach(node => translateTextNode(node, language));

  const elementRoot = root instanceof Element ? root : document.documentElement;
  translateElementAttributes(elementRoot, language);
  elementRoot.querySelectorAll('*').forEach(element => translateElementAttributes(element, language));
  isApplyingTranslation = false;
};

function TranslationRuntime({ language }: { language: Language }) {
  useEffect(() => {
    translateTree(document.body, language);

    const observer = new MutationObserver((mutations) => {
      if (isApplyingTranslation) return;
      requestAnimationFrame(() => {
        isApplyingTranslation = true;
        for (const mutation of mutations) {
          mutation.addedNodes.forEach(node => {
            if (node.nodeType === Node.TEXT_NODE) {
              translateTextNode(node as Text, language);
            } else if (node.nodeType === Node.ELEMENT_NODE) {
              translateTree(node as Element, language);
            }
          });
          if (mutation.type === 'characterData' && mutation.target.nodeType === Node.TEXT_NODE) {
            const textNode = mutation.target as Text;
            translateTextNode(textNode, language);
          }
        }
        isApplyingTranslation = false;
      });
    });

    observer.observe(document.body, {
      childList: true,
      characterData: true,
      subtree: true,
    });

    return () => observer.disconnect();
  }, [language]);

  return null;
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    const stored = window.localStorage.getItem('salesboost-ai-language') as Language | null;
    return stored && ['zh', 'en', 'id'].includes(stored) ? stored : 'zh';
  });

  useEffect(() => {
    window.localStorage.setItem('salesboost-ai-language', language);
  }, [language]);

  const value = useMemo<I18nContextValue>(() => ({
    language,
    setLanguage,
    t: (text: string) => translateText(text, language),
  }), [language]);

  return (
    <I18nContext.Provider value={value}>
      <TranslationRuntime language={language} />
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used inside I18nProvider');
  }
  return context;
}
